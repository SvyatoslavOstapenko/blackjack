CREATE TABLE public.chip_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id integer NOT NULL REFERENCES public.players(id),
    round_id integer,
    kind varchar(16) NOT NULL,
    delta integer NOT NULL,
    balance_after integer NOT NULL,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_chip_transaction_kind CHECK (
        kind IN ('opening', 'stake', 'payout', 'credit', 'reset', 'round_reversal')
    ),
    CONSTRAINT ck_chip_transaction_balance CHECK (balance_after >= 0),
    CONSTRAINT ck_chip_transaction_delta CHECK (
        (kind IN ('opening', 'payout') AND delta >= 0)
        OR (kind = 'credit' AND delta > 0)
        OR (kind = 'stake' AND delta < 0)
        OR kind IN ('reset', 'round_reversal')
    )
);

CREATE INDEX ix_chip_transactions_player_id
ON public.chip_transactions (player_id);

